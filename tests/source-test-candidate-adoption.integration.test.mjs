import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { Readable } from 'node:stream';
import { handleSourceTestRoutes } from '../src/interfaces/http/source-test-routes.ts';

test('candidate preview/import binds current job to persisted run and only imports hash-matched node tests', async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'tp-source-adoption-'));
  try {
    const runId = 'run-output'; const jobId = '11111111-1111-4111-8111-111111111111';
    const folder = path.join(root, runId); const workspace = path.join(folder, 'workspace');
    await mkdir(path.join(workspace, 'tests'), { recursive: true });
    const source = "import test from 'node:test'; test('candidate',()=>{});\n";
    await writeFile(path.join(workspace, 'tests', 'candidate.test.js'), source);
    const digest = createHash('sha256').update(source).digest('hex');
    const digests = { 'tests/candidate.test.js': digest };
    const candidateDigest = createHash('sha256').update(JSON.stringify(digests)).digest('hex');
    const run = { id: runId, status: 'candidate', executionState: 'completed', candidateFilesDigest: candidateDigest, candidateFileDigests: digests, evidenceIds:['execution-1','tool-1'], runtimeStatus: 'failed', executions: [{ id: 'execution-1', status: 'failed', files: ['tests/candidate.test.js'], evidenceId: 'execution-1' }] };
    const cases = [{ id: 'source-1', title: 'candidate test', file: 'tests/candidate.test.js', fileDigest: digest, command: { bin: 'node', args: ['--test', 'tests/candidate.test.js'], cleanEnvironment: true } }];
    await writeFile(path.join(folder, 'run.json'), JSON.stringify(run));
    await writeFile(path.join(folder, 'suite.candidate.json'), JSON.stringify({ provenance: { runId: 'tampered-run', candidateDigest: 'tampered', evidenceIds: ['fake-evidence'], findings: [{caseId:'FAKE'}] }, cases: [{...cases[0],command:{bin:'powershell',args:['-Command','bad']}}] }));
    const result = { id: runId, status: 'candidate', executionState: 'completed', runtimeStatus: 'failed', evidenceIds:run.evidenceIds, executions: run.executions, assessment: { summary:'Observed a boundary mismatch; exact business intent needs confirmation.', blockers:['Requirement owner must confirm whether 9999 is an accepted quantity.'], findings: [{caseId:'QTY-1',status:'failed',evidence:'tool-1 tool-999 execution-1'}] }, candidateFilesDigest: candidateDigest, candidateFileDigests: digests, reportPath: path.join(folder, 'report.md'), workspacePath: workspace };
    const job = { id: jobId, profileId: 'profile-fixture', mode: 'generate', status: 'candidate', result };
    let launchCount = 0;
    const jobs = { get: id => id === jobId ? job : undefined, list: () => [job], activeCount: () => 0, launch(){launchCount++;}, cancel(){} };
    let imported;
    const deps = { jobs, profiles: [{ id: 'profile-fixture', name: 'fixture', suiteName: 'fixture' }], loadProfile: async()=>({sourceRoot:workspace}), loadResume:async()=>({}), containsCredentialLikeValue:value=>/password\s*[:=]/i.test(value), outputRoot:root, importCandidate:async(profileId, candidate)=>{imported={profileId,candidate};return {status:'candidate'};} };
    const request = Readable.from([]); request.method = 'GET'; request.headers = {};
    const response = { writeHead(status){this.statusCode=status;}, end(body){this.body=body;} };
    await handleSourceTestRoutes(request, response, `/api/source-test-jobs/${jobId}/candidate`, deps);
    assert.equal(response.statusCode, 200);
    const preview = JSON.parse(response.body);
    assert.equal(preview.provenance.runtimeConclusion, 'failed');
    assert.equal(preview.provenance.assessmentSummary, result.assessment.summary);
    assert.deepEqual(preview.provenance.blockers, result.assessment.blockers);
    assert.equal(preview.provenance.runId, runId);
    assert.deepEqual(preview.provenance.evidenceIds, ['execution-1','tool-1']);
    assert.deepEqual(preview.provenance.findings[0].evidenceRefs, ['tool-1','execution-1']);
    assert.equal(preview.files['tests/candidate.test.js'], source);
    assert.deepEqual(preview.cases[0].command.args, ['--test','tests/candidate.test.js']);
    const importRequest = Readable.from(['{}']); importRequest.method = 'POST'; importRequest.headers = {};
    const importResponse = { writeHead(status){this.statusCode=status;}, end(body){this.body=body;} };
    await handleSourceTestRoutes(importRequest, importResponse, `/api/source-test-jobs/${jobId}/import`, deps);
    assert.equal(importResponse.statusCode, 201);
    assert.equal(imported.profileId, 'profile-fixture');
    assert.equal(imported.candidate.runtimeConclusion, 'failed');
    assert.equal(imported.candidate.sourceProvenance.assessmentSummary, result.assessment.summary);
    assert.deepEqual(imported.candidate.sourceProvenance.blockers, result.assessment.blockers);
    assert.deepEqual(imported.candidate.sourceProvenance, preview.provenance);
    assert.doesNotMatch(JSON.stringify(imported.candidate.sourceProvenance), /tampered-run|fake-evidence/);
    assert.ok(!imported.candidate.sourceProvenance.findings[0].evidenceRefs.includes('tool-999'));
    assert.deepEqual(imported.candidate.suite.cases[0].command.args, ['--test', 'tests/candidate.test.js']);
    assert.equal(launchCount, 0);
    for (const status of ['blocked','not-run']) {
      job.result.runtimeStatus = status;
      const blockedResponse = { writeHead(value){this.statusCode=value;}, end(body){this.body=body;} };
      await handleSourceTestRoutes(request, blockedResponse, `/api/source-test-jobs/${jobId}/candidate`, deps);
      assert.equal(blockedResponse.statusCode, 409);
    }
    job.result.runtimeStatus = 'failed';
    job.result.candidateFilesDigest = 'tampered';
    const mismatchResponse = { writeHead(value){this.statusCode=value;}, end(body){this.body=body;} };
    await handleSourceTestRoutes(request, mismatchResponse, `/api/source-test-jobs/${jobId}/candidate`, deps);
    assert.equal(mismatchResponse.statusCode, 409);
    job.result.candidateFilesDigest = candidateDigest;
    await writeFile(path.join(workspace, 'tests', 'candidate.test.js'), source + '// tampered after execution\n');
    const changedResponse = { writeHead(value){this.statusCode=value;}, end(body){this.body=body;} };
    await handleSourceTestRoutes(request, changedResponse, `/api/source-test-jobs/${jobId}/candidate`, deps);
    assert.equal(changedResponse.statusCode, 409);
    await writeFile(path.join(workspace, 'tests', 'candidate.test.js'), source);
    const secretSource = "// password=supersecret\n" + source;
    const secretDigest = createHash('sha256').update(secretSource).digest('hex');
    const secretFiles = { 'tests/candidate.test.js': secretDigest };
    const secretFilesDigest = createHash('sha256').update(JSON.stringify(secretFiles)).digest('hex');
    await writeFile(path.join(workspace, 'tests', 'candidate.test.js'), secretSource);
    await writeFile(path.join(folder, 'run.json'), JSON.stringify({ ...run, candidateFileDigests: secretFiles, candidateFilesDigest: secretFilesDigest }));
    job.result.candidateFileDigests = secretFiles; job.result.candidateFilesDigest = secretFilesDigest;
    const secretResponse = { writeHead(value){this.statusCode=value;}, end(body){this.body=body;} };
    await handleSourceTestRoutes(request, secretResponse, `/api/source-test-jobs/${jobId}/candidate`, deps);
    assert.equal(secretResponse.statusCode, 409);
    await writeFile(path.join(workspace, 'tests', 'candidate.test.js'), source);
    job.result.workspacePath = path.join(root, 'outside-workspace');
    const escapedResponse = { writeHead(status){this.statusCode=status;}, end(body){this.body=body;} };
    await handleSourceTestRoutes(request, escapedResponse, `/api/source-test-jobs/${jobId}/candidate`, deps);
    assert.equal(escapedResponse.statusCode, 409);
  } finally { await rm(root, { recursive: true, force: true }); }
});
